"""Export a CPCC (China Copyright Protection Center) source code PDF.

Fixed layout: 60 pages, 50 code lines per page, 3000 lines total.

  * first 30 pages  come from the core / back end / config pool
  * last 30 pages   come from the front end / UI / render pool

Safety rules:

  * sources are decoded as utf-8-sig first, so a BOM never leaks a stray
    prefix character into line 1 of the PDF
  * non BMP characters (emoji and similar) are escaped as \\U0001F600 so the
    embedded fonts never render them as empty boxes
  * lines wider than the frame are soft wrapped with a 4 space indent, never
    truncated
  * page header is centered as "{name} {version}", page footer is right
    aligned as "第 X 页 / 共 60 页"

Usage:
    python export_source_pdf.py --root D:/proj --name "智能排课系统" --version V1.0
    python export_source_pdf.py --root D:/proj --name "智能排课系统" --dry-run
"""

