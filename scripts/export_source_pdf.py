def first_existing(override: str | None, candidates: list[str]) -> str | None:
    if override:
        p = Path(override)
        if not p.exists():
            die("font not found: " + override)
        return str(p)
    for cand in candidates:
        if Path(cand).exists():
            return cand
    return None


def register_fonts(mono_path: str, cjk_path: str, mono_index: int, cjk_index: int) -> tuple[str, str]:
    try:
        from reportlab.pdfbase import pdfmetrics
        from reportlab.pdfbase.ttfonts import TTFont
    except ImportError:
        die("reportlab is required: pip install reportlab")

    mono_name, cjk_name = "SCMono", "SCCJK"
    try:
        pdfmetrics.registerFont(TTFont(mono_name, mono_path, subfontIndex=mono_index))
    except Exception as exc:  # noqa: BLE001
        die("failed to embed monospace font %s: %s" % (mono_path, exc))
    try:
        pdfmetrics.registerFont(TTFont(cjk_name, cjk_path, subfontIndex=cjk_index))
    except Exception as exc:  # noqa: BLE001
        die("a CJK font is mandatory because the software name is Chinese; "
            "failed to embed %s: %s" % (cjk_path, exc))
    return mono_name, cjk_name


def glyph_coverage(font_name: str) -> set[int]:
    try:
        from reportlab.pdfbase import pdfmetrics
        face = pdfmetrics.getFont(font_name).face
        table = getattr(face, "charToGlyph", None)
        if not table:
            return set()
        return {int(k) for k in table.keys()}
    except Exception:  # noqa: BLE001
        return set()


def missing_glyphs(lines: list[str], cjk_name: str) -> list[str]:
    covered = glyph_coverage(cjk_name)
    if not covered:
        return []
    seen: dict[str, None] = {}
    for line in lines:
        for ch in line:
            if ord(ch) >= 128 and ord(ch) not in covered:
                seen.setdefault(ch, None)
    return sorted(seen.keys())


def draw_code_line(c, x: float, y: float, text: str, mono: str, cjk: str,
                   size: float, col_w: float, cjk_size: float) -> None:
    cursor = x
    for match in RUN_RE.finditer(text):
        seg = match.group(0)
        if seg.isascii():
            c.setFont(mono, size)
            c.drawString(cursor, y, seg)
            cursor += col_w * len(seg)
        else:
            c.setFont(cjk, cjk_size)
            c.drawString(cursor, y, seg)
            cursor += col_w * 2 * len(seg)


def cjk_scale_ratio(cjk_name: str) -> float:
    from reportlab.pdfbase import pdfmetrics
    probe = pdfmetrics.stringWidth("中", cjk_name, 100.0)
    return (probe / 100.0) if probe else 1.0


def build_pdf(out_path: Path, pages: list[list[str]], name: str, version: str,
              mono: str, cjk: str, size: float, leading: float) -> None:
    from reportlab.pdfgen import canvas
    from reportlab.pdfbase import pdfmetrics

    out_path.parent.mkdir(parents=True, exist_ok=True)
    col_w = pdfmetrics.stringWidth("0", mono, size)
    ratio = cjk_scale_ratio(cjk)
    cjk_size = (2.0 * col_w) / ratio
    total = len(pages)
    c = canvas.Canvas(str(out_path), pagesize=(PAGE_W, PAGE_H))
    c.setTitle("%s %s 源代码" % (name, version))
    c.setSubject("计算机软件著作权登记源代码")
    c.setCreator("Cn_Software_Copyright skill")
    header_y = PAGE_H - MARGIN_TOP
    body_top = header_y - HEADER_GAP

    for idx, lines in enumerate(pages, start=1):
        c.setFont(cjk, 9)
        c.drawCentredString(PAGE_W / 2.0, header_y, "%s %s" % (name, version))
        c.setLineWidth(0.4)
        c.setStrokeGray(0.55)
        c.line(MARGIN_LEFT, header_y - 7, PAGE_W - MARGIN_RIGHT, header_y - 7)
        c.setFillGray(0.0)

        y = body_top
        for line in lines:
            if line:
                draw_code_line(c, MARGIN_LEFT, y, line, mono, cjk, size, col_w, cjk_size)
            y -= leading

        c.setFont(cjk, 8)
        c.drawRightString(PAGE_W - MARGIN_RIGHT, FOOTER_Y,
                          "第 %d 页 / 共 %d 页" % (idx, total))
        c.showPage()

    c.save()


