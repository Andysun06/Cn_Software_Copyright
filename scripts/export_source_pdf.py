def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Export a 60 page CPCC software copyright source code PDF.")
    p.add_argument("--root", required=True, help="project root directory")
    p.add_argument("--name", required=True, help="software full name, page header")
    p.add_argument("--version", default="V1.0", help="version string, default V1.0")
    p.add_argument("--out", default=None, help="output pdf path")
    p.add_argument("--pages", type=int, default=60, help="total pages, default 60")
    p.add_argument("--lines-per-page", type=int, default=50, help="code lines per page, default 50")
    p.add_argument("--front-pages", type=int, default=30, help="pages from core pool, default 30")
    p.add_argument("--keep-blank", action="store_true", help="keep blank source lines")
    p.add_argument("--max-lines-per-file", type=int, default=600, help="cap per file, 0 means no cap")
    p.add_argument("--include-tests", action="store_true", help="include test and example code")
    p.add_argument("--include-backdoor", action="store_true", help="keep files with test backdoors")
    p.add_argument("--font-mono", default=None, help="override monospace font path")
    p.add_argument("--font-cjk", default=None, help="override CJK font path")
    p.add_argument("--font-mono-index", type=int, default=0, help="ttc subfont index for mono")
    p.add_argument("--font-cjk-index", type=int, default=0, help="ttc subfont index for cjk")
    p.add_argument("--font-size", type=float, default=8.5, help="code font size, default 8.5")
    p.add_argument("--manifest", default=None, help="selection manifest json path")
    p.add_argument("--dry-run", action="store_true", help="report selection only")
    p.add_argument("--allow-short", action="store_true", help="allow fewer than required lines")
    p.add_argument("--ignore-missing-glyphs", action="store_true",
                   help="continue even if the CJK font lacks some glyphs")
    p.add_argument("--fail-on-nonbmp", action="store_true",
                   help="abort when emoji or other non BMP characters are found")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = Path(args.root).expanduser()
    if not root.is_dir():
        die("root is not a directory: %s" % root)

    total_lines = args.pages * args.lines_per_page
    if args.front_pages >= args.pages:
        die("--front-pages must be smaller than --pages")
    front_quota = args.front_pages * args.lines_per_page
    back_quota = total_lines - front_quota

    mono_path = first_existing(args.font_mono, MONO_CANDIDATES)
    cjk_path = first_existing(args.font_cjk, CJK_CANDIDATES)
    if not mono_path:
        die("no monospace font found; pass --font-mono")
    if not cjk_path:
        die("no CJK font found; pass --font-cjk")

    from reportlab.pdfbase.ttfonts import TTFont
    probe = TTFont("probe", mono_path, subfontIndex=args.font_mono_index)
    col_w = probe.stringWidth("0", args.font_size)
    body_w = PAGE_W - MARGIN_LEFT - MARGIN_RIGHT
    max_cols = max(20, int(body_w / col_w) - 1)
    usable_h = PAGE_H - MARGIN_TOP - HEADER_GAP - (FOOTER_Y + 22.0)
    leading = min(14.6, usable_h / max(1, args.lines_per_page - 1))

    core, ui, stats = collect_files(
        root, args.include_tests, not args.keep_blank, max_cols,
        args.max_lines_per_file, skip_backdoor=not args.include_backdoor)

    core_lines = sum(len(f.printed) for f in core)
    ui_lines = sum(len(f.printed) for f in ui)

    print("[INFO] root        : %s" % root)
    print("[INFO] core files  : %d (%d printable lines)" % (len(core), core_lines))
    print("[INFO] ui files    : %d (%d printable lines)" % (len(ui), ui_lines))
    print("[INFO] max columns : %d, leading %.2fpt, font %.1fpt" % (max_cols, leading, args.font_size))
    if stats["bom_files"]:
        print("[INFO] stripped BOM from %d source files" % stats["bom_files"])
    if stats["skipped_backdoor"]:
        print("[INFO] skipped backdoor files: %d" % stats["skipped_backdoor"])
    if stats["skipped_generated"]:
        print("[INFO] skipped generated files: %d" % stats["skipped_generated"])
    if stats["escaped_nonbmp"]:
        print("[WARN] escaped %d non BMP characters (%s)" % (
            stats["escaped_nonbmp"], ", ".join(stats["emoji_samples"][:8])))
        if args.fail_on_nonbmp:
            die("non BMP characters present; clean them or drop --fail-on-nonbmp")

    used: dict[str, int] = {}
    picked: list[dict] = []
    front = take(core, front_quota, used, picked, "core")
    if len(front) < front_quota:
        print("[WARN] core pool short by %d lines, topping up" % (front_quota - len(front)))
        front += take(ui, front_quota - len(front), used, picked, "ui-topup")
    back = take(ui, back_quota, used, picked, "ui")
    if len(back) < back_quota:
        print("[WARN] ui pool short by %d lines, topping up from core" % (back_quota - len(back)))
        back += take(core, back_quota - len(back), used, picked, "core-topup")

    lines = front + back
    print("[INFO] selected    : %d lines, target %d" % (len(lines), total_lines))

    if len(lines) < total_lines and not args.allow_short:
        print("[ERROR] %d lines short. Options: add modules, raise --max-lines-per-file, "
              "enable --include-tests, or pass --allow-short." % (total_lines - len(lines)),
              file=sys.stderr)
        return 2
    if len(lines) > total_lines:
        lines = lines[:total_lines]

    out_path = Path(args.out) if args.out else (
        root / "软著材料" / ("源代码_%s_%d页.pdf" % (args.version, args.pages)))

    if args.dry_run:
        for row in picked:
            print("  %-10s %6d lines  %s" % (row["group"], row["listed_lines"], row["path"]))
        print("[INFO] dry run only, no pdf written")
        return 0

    mono, cjk = register_fonts(mono_path, cjk_path,
                               args.font_mono_index, args.font_cjk_index)
    absent = missing_glyphs(lines, cjk)
    if absent and not args.ignore_missing_glyphs:
        die("CJK font lacks glyphs for: %s. Remove those characters from the source "
            "or pass --ignore-missing-glyphs." % " ".join("U+%04X(%s)" % (ord(c), c) for c in absent))

    pages = [lines[i:i + args.lines_per_page] for i in range(0, len(lines), args.lines_per_page)]
    if len(pages) > args.pages:
        pages = pages[:args.pages]
    build_pdf(out_path, pages, args.name, args.version, mono, cjk, args.font_size, leading)

    manifest_path = Path(args.manifest) if args.manifest else out_path.with_name("源代码清单.json")
    manifest = {
        "software": args.name,
        "version": args.version,
        "pages": len(pages),
        "lines_per_page": args.lines_per_page,
        "total_lines": len(lines),
        "front_pages": args.front_pages,
        "monospace_font": mono_path,
        "cjk_font": cjk_path,
        "max_columns": max_cols,
        "files": picked,
        "stats": stats,
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")

    print("[OK] pdf     : %s" % out_path)
    print("[OK] manifest: %s" % manifest_path)
    print("[OK] %d pages x %d lines" % (len(pages), args.lines_per_page))
    return 0


