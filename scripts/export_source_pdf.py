@dataclass
class SourceFile:
    path: Path
    rel: str
    family: str
    kind: str
    lines: list[str] = field(default_factory=list)
    printed: list[str] = field(default_factory=list)
    score: float = 0.0
    had_bom: bool = False
    escaped: list[str] = field(default_factory=list)


def die(msg: str, code: int = 1) -> None:
    print("[ERROR] " + msg, file=sys.stderr)
    raise SystemExit(code)


def read_text_lines(path: Path) -> tuple[list[str] | None, bool]:
    """Decode a source file. Returns (lines, had_bom).

    utf-8-sig comes first and the BOM bytes are removed explicitly, so a
    BOM can never survive as a leading character on the first code line.
    """
    try:
        raw = path.read_bytes()
    except OSError:
        return None, False
    had_bom = raw.startswith(BOM)
    if had_bom:
        raw = raw[3:]
    if b"\x00" in raw[:4096]:
        return None, had_bom
    text = None
    for enc in ("utf-8", "gb18030", "big5", "latin-1"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    if text is None:
        return None, had_bom
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    if lines and lines[0].startswith("\ufeff"):
        lines[0] = lines[0].lstrip("\ufeff")
    return lines, had_bom


def escape_non_bmp(text: str) -> tuple[str, list[str]]:
    """Escape characters outside the BMP so the PDF fonts stay valid."""
    out: list[str] = []
    hit: list[str] = []
    for ch in text:
        cp = ord(ch)
        if cp > 0xFFFF or 0xD800 <= cp <= 0xDFFF:
            out.append("\\U%08X" % cp)
            hit.append(ch)
        else:
            out.append(ch)
    return "".join(out), hit


def clean_line(line: str) -> tuple[str, list[str]]:
    line = line.expandtabs(4).rstrip()
    if any(ord(ch) < 0x20 for ch in line):
        line = "".join(ch for ch in line if ord(ch) >= 0x20 or ch == " ")
    return escape_non_bmp(line)


def display_width(text: str) -> int:
    return sum(1 if ord(ch) < 128 else 2 for ch in text)


def score_path(rel: str, family: str) -> float:
    parts = [p.lower() for p in Path(rel).parts[:-1]]
    hints = CORE_HINTS if family == "core" else UI_HINTS
    score = 0.0
    for part in parts:
        if part in hints:
            score += 20.0
        elif any(h in part for h in hints):
            score += 8.0
    if Path(rel).name.lower() in ENTRY_NAMES:
        score += 25.0
    suffix = Path(rel).suffix.lower()
    if suffix in {".yml", ".yaml", ".toml", ".ini", ".conf", ".cfg", ".properties"}:
        score -= 6.0
    score -= 0.5 * len(parts)
    return score


def wrap_lines(lines: list[str], max_cols: int, indent: str = "    ") -> list[str]:
    """Soft wrap by display columns. No character is ever dropped."""
    out: list[str] = []
    indent_w = display_width(indent)
    for line in lines:
        if display_width(line) <= max_cols:
            out.append(line)
            continue
        cur = ""
        cur_w = 0
        for ch in line:
            w = 1 if ord(ch) < 128 else 2
            if cur_w + w > max_cols:
                out.append(cur)
                cur = indent
                cur_w = indent_w
                if cur_w + w > max_cols:
                    out.append(cur)
                    cur = ""
                    cur_w = 0
            cur += ch
            cur_w += w
        out.append(cur)
    return out


def is_generated(path: Path, head: str) -> bool:
    if GENERATED_RE.search(head):
        return True
    name = path.name.lower()
    return name.endswith((".g.cs", ".designer.cs", ".generated.ts", ".generated.js"))


def collect_files(root: Path, include_tests: bool, strip_blank: bool,
                  max_cols: int, max_lines_per_file: int,
                  skip_backdoor: bool = True) -> tuple[list[SourceFile], dict]:
    stats = {
        "scanned": 0,
        "skipped_binary": 0,
        "skipped_generated": 0,
        "skipped_backdoor": 0,
        "bom_files": 0,
        "escaped_nonbmp": 0,
        "emoji_samples": [],
    }
    core: list[SourceFile] = []
    ui: list[SourceFile] = []

    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel_path = path.relative_to(root)
        rel = rel_path.as_posix()
        if any(part.lower() in SKIP_DIRS or part.startswith(".") for part in rel_path.parts[:-1]):
            continue
        if SKIP_NAME_RE.search(path.name):
            continue
        if not include_tests and (SKIP_PATH_RE.search(rel) or TEST_NAME_RE.search(path.name)):
            continue
        ext = path.suffix.lower()
        if ext in CORE_EXTS:
            family = "core"
        elif ext in UI_EXTS:
            family = "ui"
        else:
            continue

        raw_lines, had_bom = read_text_lines(path)
        if raw_lines is None:
            stats["skipped_binary"] += 1
            continue
        stats["scanned"] += 1
        if had_bom:
            stats["bom_files"] += 1
        head = "\n".join(raw_lines[:5])
        if is_generated(path, head):
            stats["skipped_generated"] += 1
            continue
        if skip_backdoor and BACKDOOR_RE.search("\n".join(raw_lines[:400])):
            stats["skipped_backdoor"] += 1
            continue

        lines: list[str] = []
        escaped: list[str] = []
        for raw in raw_lines:
            text, hits = clean_line(raw)
            if hits:
                escaped.extend(hits)
            if strip_blank and not text.strip():
                continue
            lines.append(text)
        if not lines:
            continue
        if len(lines) <= 2 and sum(len(x) for x in lines) > 4000:
            continue
        if max_lines_per_file and len(lines) > max_lines_per_file:
            lines = lines[:max_lines_per_file]

        item = SourceFile(
            path=path,
            rel=rel,
            family=family,
            kind=ext.lstrip("."),
            lines=lines,
            score=score_path(rel, family),
            had_bom=had_bom,
            escaped=escaped,
        )
        item.printed = wrap_lines(lines, max_cols)
        if escaped:
            stats["escaped_nonbmp"] += len(escaped)
            for ch in escaped[:20]:
                sample = "U+%04X" % ord(ch)
                if sample not in stats["emoji_samples"]:
                    stats["emoji_samples"].append(sample)
        (core if family == "core" else ui).append(item)

    key = lambda f: (-f.score, -len(f.printed), f.rel.lower())
    core.sort(key=key)
    ui.sort(key=key)
    return core, ui, stats


def take(pool: list[SourceFile], quota: int, used: dict[str, int],
         picked: list[dict], label: str) -> list[str]:
    """Consume printed lines from a pool, tracking a per file offset.

    Using an offset instead of a plain used-set lets a later top-up call
    continue inside a file that the earlier call only partially consumed.
    """
    out: list[str] = []
    for item in pool:
        if len(out) >= quota:
            break
        start = used.get(item.rel, 0)
        if start >= len(item.printed):
            continue
        need = quota - len(out)
        chunk = item.printed[start:start + need]
        if not chunk:
            continue
        used[item.rel] = start + len(chunk)
        out.extend(chunk)
        picked.append({
            "group": label,
            "path": item.rel,
            "language": item.kind,
            "source_lines": len(item.lines),
            "offset": start,
            "listed_lines": len(chunk),
            "score": round(item.score, 2),
            "had_bom": item.had_bom,
        })
    return out


